"""Slice scenario: CLI end-to-end slicing with deterministic G-code hashing.

This is the regression gate unit tests cannot give: the real executable importing a real
project, running the full slicing pipeline (plugin hooks compiled in and inert) and
exporting G-code from a clean process.

Modes:
  default            slice the fixture twice into two fresh output dirs; assert both runs
                     succeed and produce byte-identical G-code (determinism).
  --golden <file>    additionally compare the sha256 against a recorded golden. Mint a
                     golden from a trusted build with --write-golden <file>; comparing a
                     current build against a golden minted on the fork's merge-base is the
                     A/B regression protocol (see tests/e2e/README.md).
"""

import hashlib
import os
import shutil
import subprocess
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from e2elib import check

MODEL = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "resources",
                     "calib", "pressure_advance", "pa_pattern.3mf")
# The shipped calibration project embeds full project_settings.config, so the CLI path
# (model --datadir --outputdir --slice 1) runs the whole import->validate->slice->export
# cycle from a clean process. Output lands as <outputdir>/plate_1.gcode.


def slice_once(exe, datadir, outdir, timeout=600):
    os.makedirs(outdir, exist_ok=True)
    os.makedirs(datadir, exist_ok=True)
    env = dict(os.environ)
    p = subprocess.run([exe, os.path.abspath(MODEL), "--datadir", datadir,
                        "--outputdir", outdir, "--slice", "1"],
                       capture_output=True, text=True, timeout=timeout, env=env,
                       cwd=os.path.dirname(exe))
    gcode = os.path.join(outdir, "plate_1.gcode")
    return p.returncode, (gcode if os.path.exists(gcode) else None), (p.stdout or "") + (p.stderr or "")


def sha256_of(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 16), b""):
            h.update(chunk)
    return h.hexdigest()


def normalized_sha256(path):
    """Hash with volatile comment lines stripped:
      - '; generated by <app> on <date> at <time>'  -- wall-clock header
      - '; printing object ... id:<random> copy N' and '; stop printing object ...' --
        the object id is a fresh random 64-bit value per run (comment lines only; the
        geometry payloads around them are the actual gate).
    Proved by repeated two-run byte diffs; everything else must stay identical."""
    skip_prefixes = (b"; generated by ", b"; printing object ", b"; stop printing object ")
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for line in fh:
            if line.startswith(skip_prefixes):
                continue
            h.update(line)
    return h.hexdigest()


def run(exe, workdir, seed_conf=None, golden=None, write_golden=None):
    run1 = os.path.join(workdir, "slice_run1")
    run2 = os.path.join(workdir, "slice_run2")
    datadir = os.path.join(workdir, "slice_datadir")

    rc1, gcode1, log1 = slice_once(exe, datadir, run1)
    check(rc1 == 0 and gcode1, "slice run 1 failed: rc=%s out=%s log tail=%r"
          % (rc1, gcode1, log1[-500:]))
    size1 = os.path.getsize(gcode1)
    check(size1 > 10_000, "gcode suspiciously small: %d bytes" % size1)
    h1 = normalized_sha256(gcode1)

    rc2, gcode2, log2 = slice_once(exe, datadir, run2)
    check(rc2 == 0 and gcode2, "slice run 2 failed: rc=%s out=%s log tail=%r"
          % (rc2, gcode2, log2[-500:]))
    h2 = normalized_sha256(gcode2)

    check(h1 == h2, "slice output is not deterministic: %s vs %s" % (h1, h2))
    print("slice scenario: ok (deterministic gcode, %d bytes, normalized sha256=%s)" % (size1, h1))

    if write_golden:
        with open(write_golden, "w", encoding="utf-8") as fh:
            fh.write(h1 + "\n")
        print("golden written: %s" % write_golden)
    if golden:
        check(os.path.exists(golden), "golden file missing: %s" % golden)
        want = open(golden, encoding="utf-8").read().strip()
        check(h1 == want, "gcode hash drifted from golden: got %s want %s" % (h1, want))
        print("slice scenario: golden match")


if __name__ == "__main__":
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--exe", required=True)
    ap.add_argument("--work", required=True)
    ap.add_argument("--seed-conf", default="")
    ap.add_argument("--golden", default=None)
    ap.add_argument("--write-golden", default=None)
    args = ap.parse_args()
    run(args.exe, args.work, args.seed_conf or None, args.golden, args.write_golden)
